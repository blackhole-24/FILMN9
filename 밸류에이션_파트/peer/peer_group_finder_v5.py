class CompanyUniverse:
    """전종목 데이터(섹터 + 시총)를 보관하고 조회 인터페이스를 제공."""

    def __init__(self):
        self._df: Optional[pd.DataFrame] = None

    def load(self, force_refresh: bool = False) -> "CompanyUniverse":
        if self._df is not None and not force_refresh:
            return self
        print("\n[Universe] 전종목 데이터 로딩 중...")
        cap_map = fetch_mktcap_all()

        rows = []
        seen: set[str] = set()
        for ticker, info in WICS_SECTOR_MAP.items():
            if ticker in seen:
                continue
            seen.add(ticker)
            # 실시간 시총 우선, 없으면 근사값
            mktcap = cap_map.get(ticker, MKTCAP_APPROX.get(ticker, 0.0))
            rows.append({
                "ticker":      ticker,
                "name":        info["name"],
                "sector":      info["sector"],
                "mid_sector":  info["mid"],
                "mktcap":      mktcap,
                "mktcap_tier": get_mktcap_tier(mktcap),
            })

        self._df = pd.DataFrame(rows)
        print(f"[Universe] 로딩 완료: {len(self._df):,}개 종목\n")
        return self

    @property
    def df(self) -> pd.DataFrame:
        if self._df is None:
            self.load()
        return self._df

    @staticmethod
    def _normalize(text: str) -> str:
        """검색어 정규화: 소문자 변환 + 공백·특수문자 제거."""
        import re
        return re.sub(r"[\s\-_·]", "", text).lower()

    def resolve_ticker(self, query: str) -> Optional[str]:
        """기업명 또는 종목코드 → 종목코드. 대소문자·공백 무시."""
        query = query.strip()
        if query.isdigit():
            code = query.zfill(6)
            if code in self.df["ticker"].values:
                return code
            print(f"[오류] '{code}' 를 내장 테이블에서 찾을 수 없습니다.")
            return None

        q_norm = self._normalize(query)
        if "name_norm" not in self.df.columns:
            self.df["name_norm"] = self.df["name"].apply(self._normalize)

        # 1) 정규화 완전 일치
        match = self.df[self.df["name_norm"] == q_norm]
        if not match.empty:
            return match.iloc[0]["ticker"]

        # 2) 정규화 부분 일치
        match = self.df[self.df["name_norm"].str.contains(q_norm, na=False, regex=False)]
        if not match.empty:
            if len(match) == 1:
                return match.iloc[0]["ticker"]
            print(f"[안내] '{query}' 검색 결과 ({len(match)}건):")
            for _, r in match.head(10).iterrows():
                print(f"  {r['ticker']}  {r['name']}")
            choice = input("종목코드를 입력하세요: ").strip()
            return choice.zfill(6) if choice.isdigit() else None

        print(f"[오류] '{query}' 를 찾을 수 없습니다.")
        return None
    def get_company(self, ticker: str) -> Optional[dict]:
        row = self.df[self.df["ticker"] == ticker]
        return row.iloc[0].to_dict() if not row.empty else None


