def _fetch_via_fdr() -> dict[str, float]:
    """1순위: FinanceDataReader로 KRX 전종목 시총 수집 (원 단위)."""
    try:
        import FinanceDataReader as fdr
        print("  [시총] FinanceDataReader 수집 중...")
        df = fdr.StockListing("KRX")
        # 컬럼: Code, Name, Market, Marcap, ...  (Marcap = 원 단위)
        if "Marcap" not in df.columns or "Code" not in df.columns:
            print(f"  [시총] FDR 컬럼 불일치 (실제 컬럼: {df.columns.tolist()})")
            return {}
        df = df[df["Marcap"] > 0].copy()
        result = {str(row["Code"]).zfill(6): float(row["Marcap"]) for _, row in df.iterrows()}
        print(f"  [시총] FDR 완료: {len(result):,}개 종목")
        return result
    except Exception as e:
        print(f"  [시총] FDR 실패: {e}")
        return {}


