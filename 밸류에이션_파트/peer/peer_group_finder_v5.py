# 메인 유사기업 탐색 함수
# ══════════════════════════════════════════════════════════════════════════════

def find_peer_group(
    query: str,
    universe: CompanyUniverse,
    top_n: int = TOP_N,
    verbose: bool = True,
) -> list[dict]:
    """기업명 또는 종목코드 → 유사기업 Top N 반환."""
    ticker = universe.resolve_ticker(query)
    if ticker is None:
        return []
    target = universe.get_company(ticker)
    if target is None:
        print(f"[오류] {ticker} 정보를 찾을 수 없습니다.")
        return []

    if verbose:
        mktcap_str = f"{target['mktcap']:>22,.0f} 원" if target["mktcap"] > 0 else "정보없음"
        print(f"\n{'═'*62}")
        print(f"  입력 기업 : {target['name']} ({ticker})")
        print(f"  소섹터    : {target['sector']}")
        print(f"  중섹터    : {target['mid_sector']}")
        print(f"  시가총액  : {mktcap_str}")
        print(f"  시총 구간 : {TIER_LABELS[target['mktcap_tier']]}")
        print(f"{'═'*62}")

    candidates = []
    for _, row in universe.df.iterrows():
        if row["ticker"] == ticker:
            continue
        if not row["sector"] or row["sector"] in ("기타", ""):
            continue
        score = compute_similarity(target, row.to_dict())
        if score > 0:
            candidates.append({
                "ticker":      row["ticker"],
                "name":        row["name"],
                "sector":      row["sector"],
                "mktcap":      row["mktcap"],
                "mktcap_tier": row["mktcap_tier"],
                "score":       score,
            })

    # 정렬: 스코어 내림차순 → 시총 보유 여부 우선 → Tier 차이 오름차순 → 시총 내림차순
    tgt_tier = target["mktcap_tier"]
    def sort_key(x):
        has_mktcap = 1 if x["mktcap"] > 0 else 0
        tier_diff  = abs(x["mktcap_tier"] - tgt_tier)
        return (-x["score"], -has_mktcap, tier_diff, -x["mktcap"])
    candidates.sort(key=sort_key)
    # MIN_SCORE: 소섹터 일치 없이 중섹터 인접 기업만 있을 경우
    # 시총 정보까지 없으면 사실상 유사도가 낮으므로 최소 기준 적용
    MIN_SCORE = 0.15  # 중섹터 인접 + 시총 없을 때 하한선

    filtered = [c for c in candidates if c["score"] >= MIN_SCORE]
    result = filtered[:top_n]

    if verbose:
        if not result:
            print("  유사기업을 찾을 수 없습니다.\n")
        else:
            print(f"\n  ┌ 유사기업 Top {top_n} {'─'*46}┐")
            for i, c in enumerate(result, 1):
                cap_str = f"{c['mktcap']:>20,.0f}원" if c["mktcap"] > 0 else "         정보없음"
                print(f"  │ {i}. [{c['ticker']}] {c['name']:<16}"
                      f"│ {c['sector']:<20}│ {cap_str} │ {c['score']:.4f}")
            print(f"  └{'─'*59}┘")
            print(f"\n  → Peer: {', '.join(c['name'] for c in result)}\n")
        print(f"{'═'*62}\n")

    return result


