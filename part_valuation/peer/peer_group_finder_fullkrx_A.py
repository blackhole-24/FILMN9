def find_peer_group(
    query: str,
    df: pd.DataFrame,
    top_n: int = TOP_N,
    verbose: bool = True,
) -> list[dict]:
    # 종목 해소
    query = query.strip()
    ticker = None
    if query.isdigit():
        code = query.zfill(6)
        if code in df["ticker"].values:
            ticker = code
        else:
            print(f"[오류] '{code}' 를 찾을 수 없습니다.")
            return []
    else:
        import re
        q_norm = re.sub(r"[\s\-_·]", "", query).lower()
        df["_name_norm"] = df["name"].apply(lambda x: re.sub(r"[\s\-_·]","",str(x)).lower())
        m = df[df["_name_norm"] == q_norm]
        if m.empty:
            m = df[df["_name_norm"].str.contains(q_norm, na=False, regex=False)]
        if m.empty:
            print(f"[오류] '{query}' 를 찾을 수 없습니다.")
            return []
        if len(m) > 1:
            print(f"[안내] '{query}' 검색 결과 ({len(m)}건):")
            for _, r in m.head(10).iterrows():
                print(f"  {r['ticker']}  {r['name']}")
            choice = input("종목코드 입력: ").strip()
            ticker = choice.zfill(6) if choice.isdigit() else None
        else:
            ticker = m.iloc[0]["ticker"]

    if ticker is None:
        return []

    row = df[df["ticker"] == ticker]
    if row.empty:
        print(f"[오류] {ticker} 정보 없음")
        return []
    target = row.iloc[0].to_dict()

    is_monopoly = ticker in MONOPOLY_SET
    if verbose:
        cap_str = f"{target['mktcap']:>22,.0f} 원" if target["mktcap"] > 0 else "정보없음"
        multi = MULTI_SECTOR_MAP.get(ticker)
        biz   = BIZ_TAG.get(ticker, "")
        src   = target.get("source", "")
        print(f"\n{'═'*62}")
        print(f"  입력 기업 : {target['name']} ({ticker})" + (" ⚠ 독점/초대형" if is_monopoly else ""))
        print(f"  매핑 소스 : {'WICS수동' if src=='wics' else 'KRX자동'}")
        if multi:
            for sec, mid, w in multi:
                label = "주력" if w >= 0.5 else "부가"
                print(f"  [{label} {int(w*100):2d}%]  {sec} / {mid}")
        else:
            print(f"  소섹터    : {target['sector']}")
            print(f"  중섹터    : {target['mid_sector']}")
        if biz:
            print(f"  BIZ 태그  : {biz}")
        print(f"  시가총액  : {cap_str}")
        print(f"  시총 구간 : {TIER_LABELS[target['mktcap_tier']]}")
        if is_monopoly:
            print(f"  [안내] 국내 동일 소섹터 Peer 부족 → 인접 섹터까지 확장 표시")
        print(f"{'═'*62}")

    # ── 후보 수집 ───────────────────────────────────────────────────────────
    # 시총 있는 후보 / 없는 후보를 처음부터 분리해서 관리
    # → 시총 있는 후보가 top_n 이상 확보되면 시총 없는 후보는 완전 제외
    # → 부족할 경우에만 시총 없는 후보를 섹터 완전 일치 조건 하에 보충

    _NO_CAP_FILL_PENALTY = 0.70  # 시총 없는 보충 후보 score 할인 (항상 시총 있는 기업보다 하위 표시)
    _MIN_FILL_SCORE      = 0.35  # 시총 없는 보충 후보의 최소 원점수 (너무 낮은 섹터 유사도 차단)

    has_cap_cands: list[dict] = []
    no_cap_cands:  list[dict] = []

    for _, r in df.iterrows():
        if r["ticker"] == ticker:
            continue
        if r["sector"] in ("기타", ""):
            continue
        score = compute_similarity(target, r.to_dict())
        if score <= 0:
            continue
        entry = {
            "ticker":      r["ticker"],
            "name":        r["name"],
            "sector":      r["sector"],
            "mktcap":      r["mktcap"],
            "mktcap_tier": r["mktcap_tier"],
            "score":       score,
            "source":      r.get("source", ""),
            "no_cap_fill": False,
        }
        if r["mktcap"] > 0:
            has_cap_cands.append(entry)
        else:
            no_cap_cands.append(entry)

    MIN_SCORE = 0.10

    def sort_key(x):
        return (-x["score"], -x["mktcap"])

    has_cap_cands = [c for c in has_cap_cands if c["score"] >= MIN_SCORE]
    has_cap_cands.sort(key=sort_key)

    # 시총 있는 후보가 top_n 미만인 경우에만 시총 없는 후보 보충
    # 보충 조건: 원점수 _MIN_FILL_SCORE 이상 & 섹터가 target의 소섹터 중 하나와 일치
    result = list(has_cap_cands[:top_n])
    shortfall = top_n - len(result)

    if shortfall > 0:
        # target의 소섹터 집합 추출 (MULTI_SECTOR_MAP 고려)
        t_secs = _get_sectors(target)
        t_sec_set = {s for s, _, _ in t_secs}

        fill_cands = []
        for c in no_cap_cands:
            if c["score"] < _MIN_FILL_SCORE:
                continue
            # 섹터 완전 일치 여부 확인 (인접 섹터만으로 연결된 후보는 보충 제외)
            if c["sector"] not in t_sec_set:
                continue
            c = dict(c)  # 원본 보호
            c["score"]       = round(c["score"] * _NO_CAP_FILL_PENALTY, 4)
            c["no_cap_fill"] = True
            fill_cands.append(c)

        fill_cands.sort(key=sort_key)
        result.extend(fill_cands[:shortfall])

    if verbose:
        n_filled = sum(1 for c in result if c.get("no_cap_fill"))
        n_valid  = len(result)
        if not result:
            print("  유사기업을 찾을 수 없습니다.\n")
        else:
            label = f"유사기업 {n_valid}개"
            if n_valid < top_n:
                label += f"  ※ 충분한 Peer 미확보 ({n_valid}/{top_n})"
            print(f"\n  ┌ {label} {'─'*(56 - len(label))}┐")
            for i, c in enumerate(result, 1):
                cap_str = f"{c['mktcap']:>20,.0f}원" if c["mktcap"] > 0 else "         시총미공개"
                src_tag = "[KRX]" if c["source"] == "krx_auto" else "[WICS]"
                fill_tag = " ※시총미공개" if c.get("no_cap_fill") else ""
                print(f"  │ {i}. [{c['ticker']}] {c['name']:<14}"
                      f"│ {c['sector']:<20}│ {cap_str} │ {c['score']:.4f} {src_tag}{fill_tag}")
            print(f"  └{'─'*59}┘")
            if n_filled > 0:
                print(f"  ※ 시총미공개 {n_filled}개: 시총 정보 없는 보충 후보 (score ×0.70 적용)")
            print(f"\n  → Peer: {', '.join(c['name'] for c in result)}\n")
        print(f"{'═'*62}\n")

    return result


