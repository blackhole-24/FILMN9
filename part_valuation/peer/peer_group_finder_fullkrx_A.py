# Universe 빌더: WICS 수동 + KRX 자동 매핑 통합
# ══════════════════════════════════════════════════════════════════════════════
def build_universe(
    krx_desc_path: str,
    mktcap_csv_path: Optional[str] = None,
) -> pd.DataFrame:
    """
    전종목 Universe DataFrame 생성.
    - WICS_SECTOR_MAP 등록 종목: 수동 매핑 우선
    - 나머지: KRX_TO_WICS 자동 매핑
    """
    print("\n[Universe-A] 전종목 로딩 중...")
    cap_map = fetch_mktcap_all(mktcap_csv_path)

    # KRX 전종목 리스트 로딩
    krx_df = pd.read_csv(krx_desc_path, encoding="utf-8-sig")
    krx_df["Code"] = krx_df["Code"].astype(str).str.zfill(6)

    rows = []
    unmapped_industries: set[str] = set()

    for _, row in krx_df.iterrows():
        ticker = row["Code"]
        name   = row["Name"]
        industry = row.get("Industry", "")

        # ── 섹터 결정 우선순위 ──────────────────────────────────────────────
        if ticker in WICS_SECTOR_MAP:
            # 1순위: 수동 WICS 매핑
            info   = WICS_SECTOR_MAP[ticker]
            sector = info["sector"]
            mid    = info["mid"]
            source = "wics"
        elif pd.notna(industry) and industry in KRX_TO_WICS:
            # 2순위: KRX 업종 자동 매핑
            sector, mid = KRX_TO_WICS[industry]
            source = "krx_auto"
        else:
            # 매핑 불가 → 스킵 (섹터 미상)
            if pd.notna(industry) and industry:
                unmapped_industries.add(str(industry))
            source = "unknown"
            sector, mid = "기타", "기타"

        mktcap = cap_map.get(ticker, 0.0)
        rows.append({
            "ticker":      ticker,
            "name":        name,
            "sector":      sector,
            "mid_sector":  mid,
            "mktcap":      mktcap,
            "mktcap_tier": get_mktcap_tier(mktcap),
            "source":      source,
            "industry_raw": industry if pd.notna(industry) else "",
        })

    df = pd.DataFrame(rows)
    # 미매핑 종목 제외 (섹터 '기타')
    valid = df[df["sector"] != "기타"].copy()
    print(f"[Universe-A] 로딩 완료: 전체 {len(df):,}개 → 유효 {len(valid):,}개")
    print(f"  - WICS 수동: {(df['source']=='wics').sum():,}개")
    print(f"  - KRX 자동:  {(df['source']=='krx_auto').sum():,}개")
    if unmapped_industries:
        print(f"  - 미매핑 업종 ({len(unmapped_industries)}개): {sorted(unmapped_industries)[:5]} ...")
    return valid.reset_index(drop=True)


