def _load_csv_mktcap(csv_path: str) -> dict[str, float]:
    """자기주식제외 시가총액 CSV 로딩 (종목코드 6자리 zfill)."""
    try:
        df = pd.read_csv(csv_path, encoding="cp949")
        col_cap = "자기주식 제외 시가총액(A*B)"
        col_code = "종목코드"
        if col_cap not in df.columns or col_code not in df.columns:
            print(f"  [시총CSV] 컬럼 불일치: {df.columns.tolist()}")
            return {}
        df[col_code] = df[col_code].astype(str).str.zfill(6)
        result = {row[col_code]: float(row[col_cap]) for _, row in df.iterrows() if row[col_cap] > 0}
        print(f"  [시총CSV] {len(result):,}개 종목 로딩 완료")
        return result
    except Exception as e:
        print(f"  [시총CSV] 실패: {e}")
        return {}

def _fetch_via_fdr() -> dict[str, float]:
    try:
        import FinanceDataReader as fdr
        print("  [FDR] 수집 중...")
        df = fdr.StockListing("KRX")
        if "Marcap" not in df.columns or "Code" not in df.columns:
            return {}
        df = df[df["Marcap"] > 0].copy()
        result = {str(r["Code"]).zfill(6): float(r["Marcap"]) for _, r in df.iterrows()}
        print(f"  [FDR] {len(result):,}개 완료")
        return result
    except Exception as e:
        print(f"  [FDR] 실패: {e}")
        return {}

def fetch_mktcap_all(csv_path: Optional[str] = None) -> dict[str, float]:
    if csv_path and os.path.exists(csv_path):
        cap = _load_csv_mktcap(csv_path)
        if cap:
            return cap
    cap = _fetch_via_fdr()
    if cap:
        return cap
    print("  [시총] 내장 근사값 fallback")
    return {}


