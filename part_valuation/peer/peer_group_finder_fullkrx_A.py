# 배치 모드: 전종목 일괄 처리 → CSV 저장
# ══════════════════════════════════════════════════════════════════════════════
def run_batch(df: pd.DataFrame, output_path: str, top_n: int = TOP_N):
    """전종목에 대해 peer group 계산 → CSV 저장."""
    print(f"\n[배치] {len(df):,}개 종목 처리 시작...")
    results = []
    for i, row in df.iterrows():
        if row["sector"] in ("기타", ""):
            continue
        peers = find_peer_group(row["ticker"], df, top_n=top_n, verbose=False)
        peer_tickers = "|".join(p["ticker"] for p in peers)
        peer_names   = "|".join(p["name"]   for p in peers)
        peer_scores  = "|".join(f"{p['score']:.4f}" for p in peers)
        results.append({
            "ticker":       row["ticker"],
            "name":         row["name"],
            "sector":       row["sector"],
            "mid_sector":   row["mid_sector"],
            "mktcap":       row["mktcap"],
            "source":       row.get("source",""),
            "peer_tickers": peer_tickers,
            "peer_names":   peer_names,
            "peer_scores":  peer_scores,
        })
        if (i+1) % 200 == 0:
            print(f"  ... {i+1:,}/{len(df):,} 처리 중")

    out_df = pd.DataFrame(results)
    out_df.to_csv(output_path, index=False, encoding="utf-8-sig")
    print(f"[배치] 완료 → {output_path} ({len(out_df):,}개 종목)")
    return out_df


