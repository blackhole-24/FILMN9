def _mktcap_sim_log(cap_a: float, cap_b: float) -> float:
    """
    로그 스케일 연속형 시총 유사도 (0.0 ~ 1.0).
    - 완전 동일 → 1.0
    - 2배 차이   → 0.88
    - 10배 차이  → 0.60
    - 244배 차이 → 0.0  (= _MAX_LOG_DIFF 기준)
    """
    if cap_a <= 0 or cap_b <= 0:
        return 0.0
    diff = abs(_math.log(cap_a) - _math.log(cap_b))
    if diff > _MAX_LOG_DIFF:
        return -1.0   # 하드컷 신호 (compute_similarity에서 0.0 반환)
    return round(max(0.0, 1.0 - _LOG_K * diff / _math.log(10)), 4)


# [v6 _sector_score_pair 제거됨 → v7 버전으로 대체]


def _get_sectors(info: dict) -> list[tuple[str, str, float]]:
    """기업의 (소섹터, 중섹터, 가중치) 리스트 반환. 복합기업은 MULTI_SECTOR_MAP 우선."""
    ticker = info.get("ticker", "")
    if ticker in MULTI_SECTOR_MAP:
        return MULTI_SECTOR_MAP[ticker]
    return [(info["sector"], info["mid_sector"], 1.0)]


def compute_similarity(target: dict, candidate: dict) -> float:
    """
    v6 유사도 스코어 (0.0 ~ 1.0).

    [가중치]
      섹터 유사도  max 0.65  (소섹터 일치 0.50 + 중섹터 보너스 0.15)
      시총 유사도  max 0.35  (로그 스케일 연속형, 244배 초과 시 하드컷)

    [핵심 규칙]
      ① 시총 있는 기업이 시총 없는 기업보다 항상 상위
         → 시총 없으면 정규화 없이 sector_score(max 0.65) 그대로 반환
      ② 시총 차이가 ln(244배)=5.5 초과하면 score=0 (후보 제외)
         → 초대형주(삼성전자)의 소기업 peer 오염 방지
      ③ 복합기업은 사업 가중치의 교집합으로 계산
         → 삼성전자(반도체70%+가전30%) ↔ SK하이닉스 = 0.50점
    """
    t_caps   = target["mktcap"]
    c_caps   = candidate["mktcap"]
    t_ticker = target.get("ticker", "")
    c_ticker = candidate.get("ticker", "")
    use_mktcap = t_caps > 0 and c_caps > 0

    # ① 시총 하드컷 (둘 다 시총 있을 때만 적용)
    if use_mktcap:
        cap_sim = _mktcap_sim_log(t_caps, c_caps)
        if cap_sim < 0:
            return 0.0   # MAX_LOG_DIFF 초과 → 즉시 제외

    # ② 다중섹터 교집합 가중 합산
    t_secs = _get_sectors(target)
    c_secs = _get_sectors(candidate)
    sector_score = sum(
        _sector_score_pair(ts, tm, cs, cm, t_ticker, c_ticker) * tw * cw
        for ts, tm, tw in t_secs
        for cs, cm, cw in c_secs
    )

    if sector_score <= 0:
        return 0.0

    # ③ 시총 점수 합산 (없으면 섹터 점수만, 정규화 없음)
    if use_mktcap:
        total = sector_score + cap_sim * 0.35
    else:
        # 시총 정보 없음 → 섹터 점수에 0.85 페널티 적용
        # 시총 있는 동업종 기업(sector=0.50 + 소액 cap) 보다 항상 낮게 유지
        total = sector_score * 0.85

    return round(min(total, 1.0), 4)

