# 메인 유사기업 탐색 함수
# ══════════════════════════════════════════════════════════════════════════════

def find_peer_group(
    query: str,
    universe: CompanyUniverse,
    top_n: int = TOP_N,
    verbose: bool = True,
) -> list[dict]:
    """기업명 또는 종목코드 → 유사기업 Top N 반환."""
    ticker = universe.resolve_ticker(query)
    if ticker is None:
        return []
    target = universe.get_company(ticker)
    if target is None:
        print(f"[오류] {ticker} 정보를 찾을 수 없습니다.")
        return []

    is_monopoly = ticker in MONOPOLY_SET
    if verbose:
        mktcap_str = f"{target['mktcap']:>22,.0f} 원" if target["mktcap"] > 0 else "정보없음"
        multi = MULTI_SECTOR_MAP.get(ticker)
        biz   = BIZ_TAG.get(ticker, "")
        print(f"\n{'═'*62}")
        print(f"  입력 기업 : {target['name']} ({ticker})" + (" ⚠ 독점/초대형" if is_monopoly else ""))
        if multi:
            for sec, mid, w in multi:
                label = "주력" if w >= 0.5 else "부가"
                print(f"  [{label} {int(w*100):2d}%]  {sec} / {mid}")
        else:
            print(f"  소섹터    : {target['sector']}")
            print(f"  중섹터    : {target['mid_sector']}")
        if biz:
            print(f"  BIZ 태그  : {biz}")
        print(f"  시가총액  : {mktcap_str}")
        print(f"  시총 구간 : {TIER_LABELS[target['mktcap_tier']]}")
        if is_monopoly:
            print(f"  [안내] 국내 동일 소섹터 Peer 부족 → 인접 섹터까지 확장 표시")
        print(f"{'═'*62}")

    candidates = []
    for _, row in universe.df.iterrows():
        if row["ticker"] == ticker:
            continue
        if not row["sector"] or row["sector"] in ("기타", ""):
            continue
        score = compute_similarity(target, row.to_dict())
        if score > 0:
            candidates.append({
                "ticker":      row["ticker"],
                "name":        row["name"],
                "sector":      row["sector"],
                "mktcap":      row["mktcap"],
                "mktcap_tier": row["mktcap_tier"],
                "score":       score,
            })

    # score에 시총 로그 유사도가 이미 연속 반영되므로
    # score 내림차순 → (동점 시) 시총 있는 기업 우선 → 시총 내림차순
    def sort_key(x):
        has_cap = 1 if x["mktcap"] > 0 else 0
        return (-x["score"], -has_cap, -x["mktcap"])
    candidates.sort(key=sort_key)
    # MIN_SCORE: 중섹터 인접만 있고 시총 기여도 없는 경우 하한선
    MIN_SCORE = 0.10  # 최소 출력 기준 (교차섹터 필터는 compute_similarity 내부에서 처리)
    filtered = [c for c in candidates if c["score"] >= MIN_SCORE]
    result = filtered[:top_n]

    if verbose:
        if not result:
            print("  유사기업을 찾을 수 없습니다.\n")
        else:
            print(f"\n  ┌ 유사기업 Top {top_n} {'─'*46}┐")
            for i, c in enumerate(result, 1):
                cap_str = f"{c['mktcap']:>20,.0f}원" if c["mktcap"] > 0 else "         정보없음"
                print(f"  │ {i}. [{c['ticker']}] {c['name']:<16}"
                      f"│ {c['sector']:<20}│ {cap_str} │ {c['score']:.4f}")
            print(f"  └{'─'*59}┘")
            print(f"\n  → Peer: {', '.join(c['name'] for c in result)}\n")
        print(f"{'═'*62}\n")

    return result


