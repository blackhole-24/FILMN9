def _mktcap_sim_log(cap_a: float, cap_b: float) -> float:
    """
    로그 스케일 연속형 시총 유사도 (0.0 ~ 1.0).
    _MAX_LOG_DIFF 초과 시 -1.0 반환 (하드컷 신호).
    """
    if cap_a <= 0 or cap_b <= 0:
        return 0.0
    diff = abs(_math.log(cap_a) - _math.log(cap_b))
    if diff > _MAX_LOG_DIFF:
        return -1.0
    return round(max(0.0, 1.0 - _LOG_K * diff / _math.log(10)), 4)


def _get_biz_tag(ticker: str) -> str | None:
    """종목코드 → BIZ_TAG 반환. 없으면 None."""
    return BIZ_TAG.get(ticker)


def _sector_score_pair(t_sec: str, t_mid: str, c_sec: str, c_mid: str,
                       t_ticker: str = "", c_ticker: str = "") -> float:
    """
    소섹터 쌍(t, c) 간 섹터 유사도 (0.0 ~ 0.65).

    [v7 로직]
      1) 소섹터 완전 일치:
           기본 0.65
           BIZ_TAG 불일치 시 × _BIZ_MISMATCH_PENALTY (= × 0.6 → 0.39)
      2) _CROSS_SECTOR_WHITELIST 에 등재된 인접 쌍:
           0.15 (중섹터 동일 여부와 무관하게 화이트리스트 기준으로만 판단)
      3) 그 외: 0.0 → 제외
    """
    if t_sec == c_sec:
        base = 0.65
        # BIZ_TAG 불일치 패널티 (둘 다 태그가 있을 때만 적용)
        t_tag = _get_biz_tag(t_ticker)
        c_tag = _get_biz_tag(c_ticker)
        if t_tag and c_tag and t_tag != c_tag:
            base *= _BIZ_MISMATCH_PENALTY
        return base
    # 소섹터 불일치 → 화이트리스트 확인
    pair = frozenset({t_sec, c_sec})
    if pair in _CROSS_SECTOR_WHITELIST:
        return 0.15
    return 0.0


def _get_sectors(info: dict) -> list[tuple[str, str, float]]:
    """기업의 (소섹터, 중섹터, 가중치) 리스트. 복합기업은 MULTI_SECTOR_MAP 우선."""
    ticker = info.get("ticker", "")
    if ticker in MULTI_SECTOR_MAP:
        return MULTI_SECTOR_MAP[ticker]
    return [(info["sector"], info["mid_sector"], 1.0)]


def compute_similarity(target: dict, candidate: dict) -> float:
    """
    v7 유사도 스코어 (0.0 ~ 1.0).

    [파이프라인]
      Step 1. 시총 하드컷 — MAX_LOG_DIFF 초과 시 즉시 0.0 반환
      Step 2. 섹터 유사도 계산 (다중섹터 교집합 가중 합산)
              - 소섹터 일치: 0.65 (BIZ_TAG 불일치 시 ×0.6 = 0.39)
              - 화이트리스트 인접: 0.15
              - 그 외: 0.0 (제외)
      Step 3. 교차섹터 최소점수 필터 — sector_score가 인접(0.15)만으로 구성되고
              시총 기여 합산 후에도 _MIN_CROSS_SCORE 미달 시 0.0 반환
      Step 4. 시총 유사도 합산 (시총 없으면 섹터점수×0.85, 정규화 없음)

    [가중치]
      섹터 max 0.65 / 시총 0.35
    """
    t_cap = target["mktcap"]
    c_cap = candidate["mktcap"]
    t_ticker = target.get("ticker", "")
    c_ticker = candidate.get("ticker", "")
    use_mktcap = t_cap > 0 and c_cap > 0

    # Step 1: 시총 하드컷
    if use_mktcap:
        cap_sim = _mktcap_sim_log(t_cap, c_cap)
        if cap_sim < 0:
            return 0.0

    # Step 2: 섹터 유사도 (다중섹터 지원)
    t_secs = _get_sectors(target)
    c_secs = _get_sectors(candidate)

    sector_score = 0.0
    cross_only   = True   # 교차섹터(인접)만으로 구성됐는지 추적

    for t_sec, t_mid, t_w in t_secs:
        for c_sec, c_mid, c_w in c_secs:
            pair_score = _sector_score_pair(t_sec, t_mid, c_sec, c_mid, t_ticker, c_ticker)
            if pair_score > 0.15:
                cross_only = False   # 소섹터 직접 일치가 하나라도 있음
            sector_score += pair_score * t_w * c_w

    if sector_score <= 0:
        return 0.0

    # Step 3: 교차섹터 최소점수 필터
    if cross_only:
        total_with_cap = sector_score + (cap_sim * 0.35 if use_mktcap else 0)
        if total_with_cap < _MIN_CROSS_SCORE:
            return 0.0

    # Step 4: 시총 합산
    if use_mktcap:
        total = sector_score + cap_sim * 0.35
    else:
        total = sector_score * 0.85   # 시총없음 패널티

    return round(min(total, 1.0), 4)


