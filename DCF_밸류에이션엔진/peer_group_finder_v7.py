MKTCAP_TIERS = [
    (0,                    500_000_000_000),  # T0: 나노캡   ( ~ 5천억)
    (500_000_000_000,    3_000_000_000_000),  # T1: 소형주   (5천억 ~ 3조)
    (3_000_000_000_000, 10_000_000_000_000),  # T2: 중형주   (3조 ~ 10조)
    (10_000_000_000_000,30_000_000_000_000),  # T3: 대형주   (10조 ~ 30조)
    (30_000_000_000_000,100_000_000_000_000), # T4: 메가캡   (30조 ~ 100조)
    (100_000_000_000_000, float("inf")),      # T5: 초대형캡 (100조+)
]
TIER_LABELS = ["나노캡", "소형주", "중형주", "대형주", "메가캡", "초대형캡"]

def get_mktcap_tier(mktcap: float) -> int:
    """시총(원 단위)을 받아 Tier 인덱스 반환."""
    for i, (lo, hi) in enumerate(MKTCAP_TIERS):
        if lo <= mktcap < hi:
            return i
    return len(MKTCAP_TIERS) - 1


