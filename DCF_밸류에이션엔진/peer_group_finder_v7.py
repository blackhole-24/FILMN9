def _fetch_via_yfinance(tickers: list[str]) -> dict[str, float]:
    """2순위: yfinance로 개별 종목 시총 수집."""
    try:
        import yfinance as yf
        print(f"  [시총] yfinance로 {len(tickers)}개 종목 수집 중...")
        result = {}
        # 배치 요청
        symbols = [f"{t}.{_get_suffix(t)}" for t in tickers]
        batch = yf.Tickers(" ".join(symbols))
        for ticker, sym in zip(tickers, symbols):
            try:
                cap = batch.tickers[sym].fast_info.market_cap
                if cap and cap > 0:
                    result[ticker] = float(cap)
            except Exception:
                continue
        print(f"  [시총] yfinance 완료: {len(result):,}개 종목")
        return result
    except Exception as e:
        print(f"  [시총] yfinance 실패: {e}")
        return {}


def fetch_mktcap_all() -> dict[str, float]:
    """
    시총 수집 메인 함수. 3단계 fallback.
    반환: {ticker(6자리): mktcap(원)} 딕셔너리
    """
    # 1순위: FDR
    cap_map = _fetch_via_fdr()
    if cap_map:
        return cap_map
    # 2순위: yfinance
    cap_map = _fetch_via_yfinance(list(WICS_SECTOR_MAP.keys()))
    if cap_map:
        return cap_map
    # 3순위: 내장 근사값
    print("  [시총] 내장 근사값 테이블 사용")
    return dict(MKTCAP_APPROX)


