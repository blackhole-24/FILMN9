# CLI
# ══════════════════════════════════════════════════════════════════════════════

def main():
    universe = CompanyUniverse()
    universe.load()

    if len(sys.argv) > 1:
        find_peer_group(" ".join(sys.argv[1:]), universe)
        return

    print("=" * 62)
    print("  유사기업(Peer Group) 탐색기  v7.0")
    print("  기업명 또는 종목코드 입력  (종료: q)")
    print("=" * 62)
    while True:
        try:
            query = input("\n  검색 > ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\n  종료합니다.")
            break
        if not query:
            continue
        if query.lower() in ("q", "quit", "exit", "종료"):
            print("  종료합니다.")
            break
        find_peer_group(query, universe)


if __name__ == "__main__":
    main()
